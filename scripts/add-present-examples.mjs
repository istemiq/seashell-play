function escapeRegExp(s) {
  return String(s).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function altForms(value) {
  return String(value ?? '')
    .split(/[/,]/)
    .map((x) => x.trim())
    .filter(Boolean);
}

function buildPresentEn(verb) {
  const ps = verb.examples?.find((e) => e.form === 'past_simple');
  if (!ps?.en) {
    return `I ${verb.infinitive} regularly.`;
  }
  let en = ps.en;
  for (const form of altForms(verb.past_simple)) {
    en = en.replace(new RegExp(`\\b${escapeRegExp(form)}\\b`, 'gi'), verb.infinitive);
  }
  if (en === ps.en) {
    return `I ${verb.infinitive} regularly.`;
  }
  return en;
}

