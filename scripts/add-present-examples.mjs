function ruInfinitive(verb) {
  return verb.translation.split(/[,;(/]/)[0].trim().toLowerCase();
}

function buildPresentRu(verb) {
  const ps = verb.examples?.find((e) => e.form === 'past_simple');
  const inf = ruInfinitive(verb);
  const present = RU_PRESENT[inf];
  if (present && ps?.ru) {
    const m = ps.ru.trim().match(/^[яЯ]\s+\S+(.*)$/);
    const tail = m?.[1]?.trim() ?? '';
    return `Я ${present}${tail ? ` ${tail}` : '.'}`;
  }
  if (present) {
    return `Я ${present}.`;
  }
  if (ps?.ru && /^я\s/i.test(ps.ru.trim())) {
    const tail = ps.ru.trim().replace(/^я\s+\S+/i, '').trim();
    if (inf.endsWith('ать')) return `Я ${inf.slice(0, -3)}аю${tail ? ` ${tail}` : '.'}`;
    if (inf.endsWith('еть')) return `Я ${inf.slice(0, -3)}ю${tail ? ` ${tail}` : '.'}`;
    if (inf.endsWith('ить')) return `Я ${inf.slice(0, -3)}ю${tail ? ` ${tail}` : '.'}`;
    if (inf.endsWith('ти')) return `Я ${inf.slice(0, -2)}у${tail ? ` ${tail}` : '.'}`;
  }
  return `Я ${inf}.`;
}

function enrichVerb(verb) {
  const others = (verb.examples ?? []).filter((e) => e.form !== 'present');
  const examples = [
    {
      form: 'present',
      en: buildPresentEn(verb),
      ru: buildPresentRu(verb),
    },
    ...others,
  ];
  const order = { present: 0, past_simple: 1, past_participle: 2 };
  examples.sort((a, b) => (order[a.form] ?? 9) - (order[b.form] ?? 9));
  return { ...verb, examples };
}

for (const file of files) {
  const path = join(root, 'src/content', file);
  const data = JSON.parse(readFileSync(path, 'utf8'));
  const out = data.map(enrichVerb);
  writeFileSync(path, `${JSON.stringify(out, null, 2)}\n`, 'utf8');
  console.log(`updated ${file}`);
}
