const KEY_RE = /^\s*'(nav\.trainers|trainers\.[^']+|trainer\.[^']+)':.*$/;
const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

for (const repo of REPOS) {
  for (const [loc, block] of Object.entries(T)) {
    const file = path.join(repo, 'src/i18n/messages', `${loc}.js`);
    if (!fs.existsSync(file)) { console.log(`skip ${loc}: no file`); continue; }
    let src = fs.readFileSync(file, 'utf8');
    const lines = src.split('\n').filter((l) => !KEY_RE.test(l));
    src = lines.join('\n');
    const insert = Object.entries(block).map(([k, v]) => `  ${q(k)}: ${q(v)},`).join('\n');
    src = src.replace(/\n\};\s*$/, `\n\n${insert}\n};\n`);
    fs.writeFileSync(file, src);
    console.log(`${path.basename(repo)}/${loc}: ${Object.keys(block).length} keys`);
  }
}
